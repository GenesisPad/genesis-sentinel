import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import solc from "solc";

const dir = path.dirname(fileURLToPath(import.meta.url));
const contractPath = path.join(dir, "..", "src", "contracts", "V4SwapHelper.sol");
const outPath = path.join(dir, "..", "src", "contracts", "v4-swap-helper.generated.ts");

const source = readFileSync(contractPath, "utf8");

const input = {
  language: "Solidity",
  sources: {
    "V4SwapHelper.sol": { content: source }
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object"]
      }
    }
  }
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

const errors = (output.errors ?? []).filter((error) => error.severity === "error");
if (errors.length > 0) {
  for (const error of output.errors) {
    console.error(error.formattedMessage);
  }
  process.exit(1);
}
for (const warning of (output.errors ?? []).filter((error) => error.severity !== "error")) {
  console.warn(warning.formattedMessage);
}

const contract = output.contracts["V4SwapHelper.sol"]["V4SwapHelper"];
const bytecode = `0x${contract.evm.bytecode.object}`;
const abi = contract.abi;

const generated = `// AUTO-GENERATED by scripts/compile-v4-swap-helper.mjs from contracts/V4SwapHelper.sol.
// Do not edit by hand — edit the .sol source and re-run the compile script instead.

export const v4SwapHelperBytecode = "${bytecode}" as const;

export const v4SwapHelperAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

writeFileSync(outPath, generated);
console.log(`Wrote ${outPath} (${bytecode.length / 2 - 1} bytes bytecode)`);
